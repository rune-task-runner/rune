package ci

import (
	"fmt"
	"strings"
)

// Options are the parts of the workflow that do not come from the graph.
type Options struct {
	Version string // the Rune release the jobs install, without a leading v
	Branch  string // the branch whose pushes run the workflow
	// WorkDir is the Runefile's directory relative to the repository root,
	// with forward slashes; "." when it is the root.
	WorkDir string
	// Command is the line that regenerates the file, for its header.
	Command string
}

// Marker is the first line of every file Render writes. Rune replaces only
// a file that starts with it.
const Marker = "# Generated by rune ci github. Do not edit: change the Runefile, then run:"

// The paths a job keeps its bundles at. Steps that run a shell read the
// directory from $RUNNER_TEMP; action inputs use the runner context, as no
// script ever holds an expression.
const (
	stateDirShell  = `"$RUNNER_TEMP/rune-ci"`
	stateDirAction = "${{ runner.temp }}/rune-ci"
)

// installScript installs the Rune release VERSION for the runner's OS and
// architecture, checked against the release's published SHA-256 sums, as
// scripts/install.sh does.
const installScript = `set -euo pipefail
version=VERSION
case "$(uname -s)" in
  Linux) os=linux ;;
  Darwin) os=darwin ;;
  *) echo "rune: no release for $(uname -s)" >&2; exit 1 ;;
esac
case "$(uname -m)" in
  x86_64 | amd64) arch=amd64 ;;
  arm64 | aarch64) arch=arm64 ;;
  *) echo "rune: no release for $(uname -m)" >&2; exit 1 ;;
esac
archive="rune_${version}_${os}_${arch}.tar.gz"
url="https://github.com/rune-task-runner/rune/releases/download/v${version}"
dir="$RUNNER_TEMP/rune-bin"
mkdir -p "$dir"
curl -sSfL --retry 3 -o "$dir/$archive" "$url/$archive"
curl -sSfL --retry 3 -o "$dir/checksums.txt" "$url/checksums.txt"
(cd "$dir" && awk -v name="$archive" '$2 == name' checksums.txt | shasum -a 256 -c -)
tar -xzf "$dir/$archive" -C "$dir" rune
echo "$dir" >> "$GITHUB_PATH"
`

// Render writes the workflow of the graphs, one per OS. The same graphs and
// options always give the same bytes.
func Render(opts Options, graphs []*Graph) []byte {
	var w writer
	w.line(Marker)
	w.line("#   " + opts.Command)
	w.line("name: rune")
	w.line("on:")
	w.line("  push:")
	w.line("    branches: [" + quote(opts.Branch) + "]")
	w.line("  pull_request:")
	w.line("permissions:")
	w.line("  contents: read")
	if opts.WorkDir != "." && opts.WorkDir != "" {
		w.line("defaults:")
		w.line("  run:")
		w.line("    working-directory: " + quote(opts.WorkDir))
	}
	w.line("jobs:")
	ids := jobIDs(graphs)
	for _, g := range graphs {
		for _, n := range g.Nodes {
			renderJob(&w, opts, g, n, ids, len(graphs) > 1)
		}
	}
	return []byte(w.String())
}

// renderJob writes the job of one node (contracts/workflow.md).
func renderJob(w *writer, opts Options, g *Graph, n *Node, ids map[*Node]string, several bool) {
	id := ids[n]
	label := Label(n, g.OS, several)
	w.line("  " + id + ":")
	w.line("    name: " + quote(label))
	w.line("    runs-on: " + runsOn(g.OS))
	if len(n.Needs) > 0 {
		needs := make([]string, len(n.Needs))
		for i, m := range n.Needs {
			needs[i] = ids[m]
		}
		w.line("    needs: [" + strings.Join(needs, ", ") + "]")
	}
	w.line("    steps:")
	w.line("      - name: Check out")
	w.line("        uses: actions/checkout@v4")
	w.line("        with:")
	w.line("          persist-credentials: false")
	w.line("      - name: Install rune " + opts.Version)
	w.line("        shell: bash")
	w.script(strings.ReplaceAll(installScript, "VERSION", opts.Version))
	for _, a := range n.Ancestors() {
		if !a.Outputs {
			continue
		}
		w.line("      - name: Download outputs of " + ids[a])
		w.line("        uses: actions/download-artifact@v4")
		w.line("        with:")
		w.line("          name: rune-" + ids[a])
		w.line(fmt.Sprintf("          path: %s/in/%04d-%s", stateDirAction, a.Index, ids[a]))
	}
	command := commandLine(n)
	if n.Cached {
		w.line("      - name: Cache key")
		w.line("        id: key")
		w.line("        shell: bash")
		w.script("rune ci run --dir " + stateDirShell + " --key -- " + command + ` >> "$GITHUB_OUTPUT"`)
		w.line("      - name: Restore cache")
		w.line("        id: restore")
		w.line("        uses: actions/cache/restore@v4")
		w.line("        with:")
		w.line("          path: " + stateDirAction + "/bundle.tar")
		w.line("          key: ${{ steps.key.outputs.key }}")
	}
	w.line("      - name: " + quote("Run "+label))
	w.line("        shell: bash")
	w.script("rune ci run --dir " + stateDirShell + " -- " + command)
	if n.Cached {
		w.line("      - name: Save cache")
		w.line("        if: steps.restore.outputs.cache-hit != 'true'")
		w.line("        uses: actions/cache/save@v4")
		w.line("        with:")
		w.line("          path: " + stateDirAction + "/bundle.tar")
		w.line("          key: ${{ steps.key.outputs.key }}")
	}
	if n.Outputs {
		w.line("      - name: Upload outputs")
		w.line("        uses: actions/upload-artifact@v4")
		w.line("        with:")
		w.line("          name: rune-" + id)
		w.line("          path: " + stateDirAction + "/bundle.tar")
		w.line("          retention-days: 1")
		w.line("          if-no-files-found: error")
		w.line("          overwrite: true")
	}
}

// commandLine is the task and its arguments as shell words.
func commandLine(n *Node) string {
	words := []string{ShellWord(n.Task.Name)}
	for _, a := range n.Argv {
		words = append(words, ShellWord(a))
	}
	return strings.Join(words, " ")
}

// quote writes s as a single-quoted YAML scalar.
func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// writer builds the workflow text.
type writer struct{ strings.Builder }

func (w *writer) line(s string) {
	w.WriteString(s)
	w.WriteByte('\n')
}

// script writes a step's run: as a literal block, so no character of the
// script means anything to YAML.
func (w *writer) script(s string) {
	w.line("        run: |")
	for l := range strings.Lines(s) {
		w.line("          " + strings.TrimSuffix(l, "\n"))
	}
}
