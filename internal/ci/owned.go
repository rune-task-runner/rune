package ci

import (
	"bytes"
	"strings"
)

// State is how a workflow file compares with what Render would write.
type State string

// The states of a workflow file.
const (
	StateMissing      State = "missing"
	StateNotGenerated State = "not generated by rune ci github"
	StateCurrent      State = "current"
	StateStale        State = "stale"
)

// PlanFile says what a write of planned would do to a file with the bytes
// existing: nothing when it is current, refuse when Rune did not generate it.
func PlanFile(existing []byte, existed bool, planned []byte) State {
	switch {
	case !existed:
		return StateMissing
	case !Generated(existing):
		return StateNotGenerated
	case bytes.Equal(existing, planned):
		return StateCurrent
	default:
		return StateStale
	}
}

// Generated reports whether data starts with the marker line.
func Generated(data []byte) bool {
	first, _, _ := strings.Cut(string(data), "\n")
	return strings.TrimSuffix(first, "\r") == Marker
}
