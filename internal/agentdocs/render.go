package agentdocs

import (
	"errors"
	"fmt"
	"strings"
)

// The limits of a skill (spec 056 FR-032). Up to inlineLimit tasks the
// entries are in SKILL.md. Above it they are in tasks.md, and SKILL.md has an
// index of at most indexLimit lines, so its length has a bound.
const (
	inlineLimit = 30
	indexLimit  = 100
)

// The files of a skill.
const (
	SkillFile = "SKILL.md"
	TasksFile = "tasks.md"
)

// DefaultSkillName names the skill Rune writes to its documented location.
const DefaultSkillName = "rune-tasks"

// maxSkillName and maxDescription are limits of the Agent Skills format.
// descriptionBudget leaves room below the second one.
const (
	maxSkillName      = 64
	maxDescription    = 1024
	descriptionBudget = 900
)

// generalText is what every export says before the entries. It names no way
// around a confirmation, and it says that the text enforces nothing.
const generalText = "## Rune tasks\n" +
	"\n" +
	"This project's commands are tasks of its Runefile. Run a task with `rune <task>` from any directory of the project. When a task below does what you need, run the task and not a command of your own.\n" +
	"\n" +
	"- Arguments are values in the order the usage shows: `<name>` is required, `[name]` is optional, and `...` after either takes several values. `name=value` does not pass a parameter.\n" +
	"- Quote a value that has a space or a shell character. The examples are written for a POSIX shell.\n" +
	"- A task that asks a person to confirm, or that applies a plan a person approved, waits for that person at a terminal. Ask the person to run it. Do not answer in their place, and do not look for another way to do its work.\n" +
	"- Where an entry says which value the author allows agents, use that value and no other.\n" +
	"- This text is guidance. It does not limit what a shell can run. Rune enforces confirmations and the values allowed for agents only for calls through its MCP server, `rune mcp`.\n" +
	"- The entries are generated from the Runefile and list every public task, also those for another operating system. `rune --list` shows the tasks this machine can run.\n"

const noTasksText = "This Runefile has no public tasks."

// The marker lines. A begin line and a generated line carry the fingerprint
// between their prefix and the closing "-->".
const (
	beginPrefix     = "<!-- rune:begin tasks"
	endLine         = "<!-- rune:end tasks -->"
	generatedPrefix = "<!-- rune:generated claude-skill"
	markerSuffix    = "-->"
)

const (
	sectionNote = "<!-- Generated by `rune export agents-md` from the Runefile. Do not edit between the rune:begin and rune:end lines: change the Runefile and run the command again. -->"
	skillNote   = "<!-- Generated by `rune export claude-skill` from the Runefile. Do not edit: change the Runefile and run the command again. -->"
)

// Body is the text both formats hold: the general text and the entries.
func Body(c Catalog) string {
	return generalText + "\n" + entries(c)
}

// entries renders every entry, with one empty line between two.
func entries(c Catalog) string {
	if len(c.Entries) == 0 {
		return noTasksText
	}
	texts := make([]string, len(c.Entries))
	for i, e := range c.Entries {
		texts[i] = entryText(e)
	}
	return strings.Join(texts, "\n\n")
}

var systemNames = map[string]string{
	"linux":   "Linux",
	"macos":   "macOS",
	"windows": "Windows",
	"unix":    "Unix (every system but Windows)",
}

// entryText renders one entry. The order of its lines is fixed: what the
// task is, how it is called, then what limits it.
func entryText(e Entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "### `%s`\n\n", e.Name)
	if doc := prose(e.Doc); doc != "" {
		b.WriteString(doc + "\n\n")
	}
	lines := []string{"Usage: `" + e.Usage() + "`"}
	if ex := e.Example(); ex != "" {
		lines = append(lines, "Example: `"+ex+"`")
	}
	var own []Allowed
	for _, p := range e.Params {
		lines = append(lines, paramText(p))
		if p.AgentValue != nil {
			own = append(own, Allowed{Param: p.Name, Value: *p.AgentValue})
		}
	}
	if e.Group != "" {
		lines = append(lines, "Group: "+value(e.Group))
	}
	if len(e.OS) > 0 {
		systems := make([]string, len(e.OS))
		for i, os := range e.OS {
			systems[i] = systemNames[os]
		}
		lines = append(lines, "Runs only on: "+strings.Join(systems, ", ")+".")
	}
	if returns := prose(e.Returns); returns != "" {
		lines = append(lines, "Returns: "+returns)
	}
	switch {
	case e.Confirm && e.Question != "":
		lines = append(lines, "Asks a person to confirm: "+value(e.Question)+". Ask the person to run it.")
	case e.Confirm:
		lines = append(lines, "Asks a person to confirm. Ask the person to run it.")
	}
	for _, r := range e.Reaches {
		if r.Confirm {
			lines = append(lines, "A run can reach `"+r.Name+"`, which asks a person to confirm.")
		}
	}
	if len(own) > 0 {
		lines = append(lines, "The author allows agents only "+allowedText(own)+".")
	}
	for _, r := range e.Reaches {
		if len(r.Allow) > 0 {
			lines = append(lines, "A run can reach `"+r.Name+"`, where the author allows agents only "+allowedText(r.Allow)+".")
		}
	}
	if e.Plan {
		lines = append(lines, "Makes a plan that Rune stores.")
	}
	if e.Applies != "" {
		lines = append(lines, "Applies the plan of `"+e.Applies+"` after a person approved it. Ask the person to run it.")
	}
	if e.ReadOnly {
		lines = append(lines, "Declared read-only by its author.")
	}
	if e.Network {
		lines = append(lines, "Declared to use the network by its author.")
	}
	b.WriteString("- " + strings.Join(lines, "\n- "))
	return b.String()
}

func allowedText(allow []Allowed) string {
	parts := make([]string, len(allow))
	for i, a := range allow {
		parts[i] = "`" + a.Param + "` = " + value(a.Value)
	}
	return strings.Join(parts, " and ")
}

var kindNames = map[ParamKind]string{
	Required:   "required",
	Optional:   "optional",
	OneOrMore:  "one or more values",
	ZeroOrMore: "zero or more values",
}

// paramText is the line of one parameter: its kind, type and default, then
// the author's text. The value the author allows agents is a limit of the
// task and has its own line.
func paramText(p Param) string {
	parts := []string{kindNames[p.Kind]}
	switch p.Type {
	case "number":
		parts = append(parts, "a number")
	case "boolean":
		parts = append(parts, "`true` or `false`")
	case "path":
		parts = append(parts, "a path")
	case "raw":
		parts = append(parts, "split into shell words without quoting")
	case "enum":
		values := make([]string, len(p.Enum))
		for i, v := range p.Enum {
			values[i] = value(v)
		}
		parts = append(parts, "one of "+strings.Join(values, ", "))
	}
	switch {
	case p.HasDefault && p.Literal:
		parts = append(parts, "default "+value(p.Default))
	case p.HasDefault:
		parts = append(parts, "default "+code(p.Default)+", worked out when the task runs")
	}
	line := "`" + p.Name + "`: " + strings.Join(parts, ", ") + "."
	if doc := prose(p.Doc); doc != "" {
		line += " " + doc
	}
	return line
}

// Section is the agents-md export: the body between Rune's two marker
// lines, which is what Rune owns in a Markdown file.
func Section(c Catalog) string {
	return beginPrefix + " fingerprint=" + c.Fingerprint() + " " + markerSuffix + "\n" +
		sectionNote + "\n\n" +
		Body(c) + "\n\n" +
		endLine + "\n"
}

// CheckSkillName says why name cannot be the name of a skill, which is also
// the name of its directory.
func CheckSkillName(name string) error {
	ok := name != "" && len(name) <= maxSkillName &&
		!strings.HasPrefix(name, "-") && !strings.HasSuffix(name, "-") && !strings.Contains(name, "--") &&
		!strings.ContainsFunc(name, func(r rune) bool {
			return (r < 'a' || r > 'z') && (r < '0' || r > '9') && r != '-'
		})
	if ok {
		return nil
	}
	return errors.New("a skill name is 1 to 64 characters of lowercase letters, digits and single hyphens, and does not start or end with a hyphen")
}

// SkillFiles is the claude-skill export: the text of SKILL.md and of
// tasks.md, which is empty when the entries fit into SKILL.md.
func SkillFiles(c Catalog, name string) (skill, tasks string) {
	generated := generatedPrefix + " fingerprint=" + c.Fingerprint() + " " + markerSuffix + "\n" + skillNote + "\n\n"
	head := "---\n" +
		"name: " + yamlString(name) + "\n" +
		"description: " + yamlString(skillDescription(c)) + "\n" +
		"---\n\n" + generated
	if len(c.Entries) <= inlineLimit {
		return head + Body(c) + "\n", ""
	}
	tasks = generated +
		"## Rune tasks: entries\n\n" +
		"How to call a task and what its limits mean is in [SKILL.md](SKILL.md).\n\n" +
		entries(c) + "\n"
	return head + generalText + "\n" + index(c) + "\n", tasks
}

// index stands in SKILL.md for the entries of a large catalog: one line per
// task up to indexLimit, and the number of tasks beyond it.
func index(c Catalog) string {
	var b strings.Builder
	fmt.Fprintf(&b, "### Index\n\nThe Runefile has %d public tasks. [tasks.md](tasks.md) has an entry for each, with its parameters and limits. Read a task's entry before you run it.\n", len(c.Entries))
	for _, e := range c.Entries[:min(len(c.Entries), indexLimit)] {
		b.WriteString("\n- `" + e.Usage() + "`")
		if s := summary(e.Doc); s != "" {
			b.WriteString(": " + s)
		}
	}
	switch more := len(c.Entries) - indexLimit; {
	case more == 1:
		b.WriteString("\n- 1 more task is in [tasks.md](tasks.md).")
	case more > 1:
		fmt.Fprintf(&b, "\n- %d more tasks are in [tasks.md](tasks.md).", more)
	}
	return b.String()
}

// skillDescription says what the skill holds and when to read it. A client
// keeps it in context for every session and decides from it whether to load
// the skill, so it names the tasks, within a budget.
func skillDescription(c Catalog) string {
	const (
		before = "Tasks of this project's Runefile and the rune command line for each: "
		after  = ". Read it before you run a build, a test, a deploy or another project command."
	)
	if len(c.Entries) == 0 {
		return before + "none yet" + after
	}
	names := make([]string, len(c.Entries))
	for i, e := range c.Entries {
		names[i] = e.Name
	}
	for n := len(names); n > 0; n-- {
		list := strings.Join(names[:n], ", ")
		if left := len(names) - n; left > 0 {
			list += fmt.Sprintf(" and %d more", left)
		}
		if d := before + list + after; len(d) <= descriptionBudget {
			return d
		}
	}
	return before + fmt.Sprintf("%d tasks", len(names)) + after
}

// yamlString writes s as a double-quoted YAML scalar. The texts it is given
// are one line of ASCII; the two escapes are all a double-quoted scalar
// needs for them.
func yamlString(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}
