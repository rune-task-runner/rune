package agentdocs

import (
	"bytes"
	"strings"
)

// bom is the UTF-8 byte order mark. It is not part of a file's first line.
const bom = "\xef\xbb\xbf"

// Marker is one of Rune's marker lines found in a file.
type Marker struct {
	Line  int // 1-based
	Begin bool
}

// Refusal is why a target cannot be written or checked: its marker lines
// are not one begin line followed by one end line, or it is a skill file
// that Rune did not generate. Nothing is written when a plan ends in one.
type Refusal struct {
	Path    string   // "" for the Markdown file of agents-md, else the skill file
	Markers []Marker // the marker lines involved, in file order
}

func (r *Refusal) Error() string {
	if r.Path == "" {
		return `marker lines that are not one "rune:begin tasks" line followed by one "rune:end tasks" line`
	}
	return r.Path + " was not generated by rune export"
}

// line is one line of a file: where it starts, where its text ends, and
// where the next line starts.
type line struct {
	start, textEnd, end int
	text                string // without its line ending and trailing white space
}

func splitLines(s string) []line {
	var out []line
	for start := 0; start < len(s); {
		end := len(s)
		if i := strings.IndexByte(s[start:], '\n'); i >= 0 {
			end = start + i + 1
		}
		textEnd := start + len(strings.TrimRight(s[start:end], "\r\n"))
		out = append(out, line{start, textEnd, end, strings.TrimRight(s[start:textEnd], " \t")})
		start = end
	}
	return out
}

func isMarker(text, prefix string) bool {
	rest, ok := strings.CutPrefix(text, prefix)
	return ok && strings.HasSuffix(rest, markerSuffix) && (rest == markerSuffix || rest[0] == ' ')
}

// fingerprintOf reads the fingerprint a begin line or a generated line
// carries, or "" when it has none.
func fingerprintOf(text string) string {
	for field := range strings.FieldsSeq(text) {
		if fp, ok := strings.CutPrefix(field, "fingerprint="); ok {
			return fp
		}
	}
	return ""
}

// sameText compares two texts without regard to LF against CR LF, which a
// checkout can change.
func sameText(a, b string) bool {
	return strings.ReplaceAll(a, "\r\n", "\n") == strings.ReplaceAll(b, "\r\n", "\n")
}

// merged is the result of putting a section into a Markdown file.
type merged struct {
	text        string
	owned       bool   // the file held a section before
	fingerprint string // of that section
	changed     bool
	size        int // the bytes of the section with the file's line ending
}

// mergeSection puts section into the text of a Markdown file. A file with
// no marker line gains the section at its end. A file with one begin line
// and, after it, one end line has the lines from the one to the other
// replaced. Every byte outside them is kept, and the section takes the
// file's line ending. Any other set of marker lines is refused.
func mergeSection(old, section string) (merged, error) {
	mark := ""
	if rest, ok := strings.CutPrefix(old, bom); ok {
		mark, old = bom, rest
	}
	lines := splitLines(old)
	var markers []Marker
	begin, end := -1, -1
	for i, l := range lines {
		switch {
		case isMarker(l.text, beginPrefix):
			markers = append(markers, Marker{Line: i + 1, Begin: true})
			begin = i
		case l.text == endLine:
			markers = append(markers, Marker{Line: i + 1})
			end = i
		}
	}

	eol := "\n"
	if i := strings.IndexByte(old, '\n'); i > 0 && old[i-1] == '\r' {
		eol = "\r\n"
	}
	section = strings.ReplaceAll(section, "\n", eol)

	switch {
	case len(markers) == 0 && old == "":
		return merged{text: mark + section, changed: true, size: len(section)}, nil
	case len(markers) == 0:
		sep := eol
		if !strings.HasSuffix(old, "\n") {
			sep = eol + eol
		}
		return merged{text: mark + old + sep + section, changed: true, size: len(section)}, nil
	case len(markers) == 2 && begin >= 0 && end > begin:
		// The line ending of the end line is the file's, not Rune's.
		from, to := lines[begin].start, lines[end].textEnd
		body := strings.TrimSuffix(section, eol)
		m := merged{owned: true, fingerprint: fingerprintOf(lines[begin].text), size: len(section)}
		if sameText(old[from:to], body) {
			m.text = mark + old
			return m, nil
		}
		m.text, m.changed = mark+old[:from]+body+old[to:], true
		return m, nil
	}
	return merged{}, &Refusal{Markers: markers}
}

// generatedFingerprint reports whether a skill file is one Rune generated,
// and the fingerprint it carries.
func generatedFingerprint(old []byte) (fingerprint string, owned bool) {
	for _, l := range splitLines(string(bytes.TrimPrefix(old, []byte(bom)))) {
		if isMarker(l.text, generatedPrefix) {
			return fingerprintOf(l.text), true
		}
	}
	return "", false
}
